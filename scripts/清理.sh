#!/bin/bash
# ============================================================
# 清理 —— 删掉已合并任务的工作区目录
# ============================================================
# 用法:bash scripts/清理.sh 回到顶部
#
# 什么时候用:回收之后。确认合进来的内容没问题了,
# 就把那个独立副本删掉,免得堆积。
#
# 以后要再改这个功能,重新执行「开工.sh」即可。
# ============================================================

HERE="$(dirname "$0")"
. "$HERE/中文工具.sh"

check_name "$1"
NAME="$1"

cd "$REPO" || die "进不去工程目录"

echo ""
echo "  正在清理任务:$NAME"
echo "  ────────────────────────────────────"

# 同理:不能用管道判成败(会拿到 sed 的退出码)
# 临时日志落进 .tmp/(已被忽略)并带任务名,避免残留卡死与并发互踩
mkdir -p "$REPO/.tmp"
LOG="$REPO/.tmp/wtclean-$NAME.log"
bash "$HERE/wt-merge.sh" "$NAME" --go --cleanup > "$LOG" 2>&1
RC=$?
zh < "$LOG" | sed 's/^/  /'
rm -f "$LOG"
echo "  ────────────────────────────────────"
echo ""

if [ $RC -ne 0 ]; then
  die "清理失败(上面是原因)。
  若提示该任务还没合并,先执行:bash scripts/回收.sh $NAME 是"
fi

echo "  ✓ 清理完成。以后要再改这个功能,重新执行「开工.sh」即可。"
echo "    当前所有任务:bash scripts/看板.sh"