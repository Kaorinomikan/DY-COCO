#!/bin/bash
# ============================================================
# 回收 —— 自检 → 合并进主干 → 自动清理副本(一步完成)
# ============================================================
# 2026-10-11 用户定:小扩展开发,流程从简,且顺序固定:
#   ① 合并**前**自检(是否都提交 / 语法检查 / 版本号标签红线 / 冲突预判)
#   ② 合并进 main(共享文件冲突自动解)
#   ③ 成功后**自动清理**工作树副本与分支 —— 不需要再跑「清理」
# 「回收 / 合并 / 验收」是同一个口令。
#
# 用法:
#   bash scripts/回收.sh 回到顶部          自检+合并+自动清理,一步完成
#   bash scripts/回收.sh 回到顶部 只看     只预检,不动任何东西
#   DYC_SMOKE_OK=1 bash scripts/回收.sh <名字>
#       任务改过 src/** 或 manifest.json 时，--go 合并必须带当次真机冒烟确认
# ============================================================

HERE="$(dirname "$0")"
. "$HERE/中文工具.sh"

check_name "$1"
NAME="$1"
MODE="${2:-}"

case "$MODE" in
  ""|合并|验收|确认|是) GO="--go" ;;
  只看|预检|看看)       GO="" ;;
  *) die "第二个参数只能不写(默认合并)或「只看」(仅预检)" ;;
esac

cd "$REPO" || die "进不去工程目录"

echo ""
if [ -z "$GO" ]; then
  echo "  正在预检任务:$NAME(只看不改)"
else
  echo "  正在合并任务:$NAME(合并 + 自检一步完成)"
fi
echo "  ────────────────────────────────────"

# ⚠️ 管道会丢掉 wt-merge.sh 的退出码(给的是 sed 的)。
#    失败时若还打印「已合到主工程」就是**假的成功**,必须用 RC 判断。
# 合并成功后自动清理工作树与分支(--cleanup),不再需要手动跑「清理」。
#
# 临时日志落进 .tmp/(已被 .gitignore 忽略)并带任务名。
# 2026-10-13 整改:旧写法 .tmp-wtmerge.log 在主工作区**根目录**下,
# 不被 .gitignore 的任何规则覆盖 —— 脚本一旦被中断就会残留,
# 让主工作区永久判定为「脏」,从此所有会话既开不了任务也回收不了;
# 两个会话同时回收时还会互相覆盖对方的日志。
mkdir -p "$REPO/.tmp"
LOG="$REPO/.tmp/wtmerge-$NAME.log"
if [ -n "$GO" ]; then
  bash "$HERE/wt-merge.sh" "$NAME" --go --cleanup > "$LOG" 2>&1
else
  bash "$HERE/wt-merge.sh" "$NAME" > "$LOG" 2>&1
fi
RC=$?
zh < "$LOG" | sed 's/^/  /'
rm -f "$LOG"
echo "  ────────────────────────────────────"
echo ""

if [ $RC -ne 0 ]; then
  if [ -z "$GO" ]; then
    die "预检没通过(上面是原因)。
  预检**没有动任何代码**,解决上面列的问题后再试。"
  elif [ "$RC" -eq 2 ]; then
    die "任务已合并进本地主干，但测试档同步失败。
  本次未回滚合并，任务副本与分支保留；修复同步问题后重跑回收。"
  elif [ "$RC" -eq 3 ]; then
    die "任务已合并且测试档已同步，但任务副本或分支未清理完成。
  本次未回滚合并，请根据上面的错误检查剩余任务。"
  else
    die "回收未完成(上面是原因)。
  请按日志核对合并状态；只有日志明确显示中止成功时，才表示已回到合并前。"
  fi
fi

if [ -z "$GO" ]; then
  echo "  预检**没有动任何代码**。确认没问题后执行:"
  echo "     bash scripts/回收.sh $NAME"
else
  echo "  ✓ 已合并进主干(自检在合并前已通过,副本已自动清理)"
  echo "  ✓ 已同步一份到桌面「COCO TEST」(唯一测试档,已逐文件校验一致)"
  echo "  还没推送 —— 推送由你决定"
fi
