#!/bin/bash
# ============================================================
# 开工 —— 开一个新任务
# ============================================================
# 用法:bash scripts/开工.sh 回到顶部
#       bash scripts/开工.sh 回到顶部 "中控台右下角加回到顶部按钮"
#
# 做三件事:
#   ① 给这个任务开一份独立的代码副本(你和其他会话互不干扰)
#   ② 写一张任务卡在里面
#   ③ 打印一段可以直接发给新对话窗口的话
#
# 任务名建议用 2~8 个汉字,不要有空格。
# ============================================================

HERE="$(dirname "$0")"
. "$HERE/中文工具.sh"

check_name "$1"
NAME="$1"
DESC="${2:-开发「$NAME」功能}"

cd "$REPO" || die "进不去工程目录"

echo ""
echo "  正在开任务:$NAME"
echo "  ────────────────────────────────────"

# ⚠️ 管道会丢掉被包脚本的退出码(它给的是 sed 的)。
#    曾因此把「[中止] 主工作区脏」当成成功、照样打印「✓ 开好了」——
#    **失败被吞掉比报错危险得多**,所以必须用 PIPESTATUS 取真实退出码。
# 临时日志落进 .tmp/(已被 .gitignore 忽略)并带任务名 —— 2026-10-13 整改:
# 旧写法 .tmp-wtnew.log 在主工作区根下不被忽略,中断残留会让主工作区永久变脏。
mkdir -p "$REPO/.tmp"
LOG="$REPO/.tmp/wtnew-$NAME.log"
bash "$HERE/wt-new.sh" "$NAME" "$DESC" > "$LOG" 2>&1
RC=$?
zh < "$LOG" | sed 's/^/  /'
rm -f "$LOG"

if [ $RC -eq 0 ]; then
  echo ""
  echo "  ────────────────────────────────────"
  echo "  ✓ 开好了:$NAME"
  echo ""
  echo "  接下来两步:"
  echo ""
  echo "  ① 新开一个对话窗口,把工作目录设成:"
  echo "     $WT_ROOT/$NAME"
  echo ""
  echo "  ② 把下面这段话发给那个窗口(直接复制):"
  echo ""
  echo "  ═════════════════════════════════════════════════"
  bash "$HERE/说明.sh" "$NAME"
  echo "  ═════════════════════════════════════════════════"
  echo ""
else
  echo ""
  echo "  ────────────────────────────────────"
  die "开任务失败(上面是原因)。
  最常见的是主工程目录还有没提交的改动 ——
  先把那些改动提交掉,或者确认不是别人的在写。"
fi