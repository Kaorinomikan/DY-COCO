#!/bin/bash
# ============================================================
# 说明 —— 打印给新会话的整段话(复制给那个对话窗口)
# ============================================================
# 用法:bash scripts/说明.sh 回到顶部
#
# 这一段是「派活」用的:跨会话没法直接派活,
# 所以把它写成一段完整交代,复制给新窗口即可。
# ============================================================

HERE="$(dirname "$0")"
. "$HERE/中文工具.sh"

NAME="${1:-任务名}"
WT="$WT_ROOT/$NAME"

cat <<EOF
你的工作目录是:$WT

这是一个浏览器扩展(抖音抖店助手)的开发任务。
任务名:「$NAME」,对应分支:task/$NAME

━━━ 一、先读这三份文件 ━━━

1. $WT/AGENTS.md 的「多会话并行开发」一章
   —— 告诉你:哪些文件能改、哪些是共享文件只允许「末尾追加」、
      以及五条绝对不能碰的红线
2. $WT/docs/agents/用户要求.md
   —— 用户定的硬性规矩,优先级最高
3. $WT/开发待办.md 里跟本任务相关的部分(未开发计划统一在这里)

━━━ 二、工作目录是独立副本 ━━━

主工程目录 $REPO 你**不要碰**,
那里可能有别的开发会话正在工作。
你只改 $WT 里面的文件。

━━━ 三、怎么开工 ━━━

把 $WT/scripts/feature-template.js
复制到 $WT/src/live/$NAME.js,然后照模板里的注释做。
模板里该说的都写清楚了(要改哪几处、怎么自检、常见坑)。

━━━ 四、五条红线(违反会被回收脚本直接拦下)━━━

① 不准改 manifest.json 里的 version
② 不准推送(push)
③ 不准打标签(tag)
④ 不准改 update-manifest.json(它是推送期在主干上统一生成的清单)
⑤ 不准写 README.md / AGENTS.md / 开发日志.md 的「本版新增」
   —— 那些统一由回收方在主工程里写

━━━ 五、共享文件只能「末尾追加」━━━

$WT/src/content/flags.js 的 DYC_FLAGS_META 数组
    → 把你的开关加在**数组末尾**
$WT/manifest.json 对应页面的 js 数组
    → 把你的脚本加在**末尾**
**不要插在中间** —— 插中间会跟别的会话打架。

━━━ 六、中间态只跑快速语法；定稿后回收自动跑其余闸 ━━━

cd "$WT"
python scripts/check-syntax.py --changed

改过扩展运行内容时，真机冒烟后用 DYC_SMOKE_OK=1 bash scripts/回收.sh <名字>；
回收脚本自动检查 manifest 顺序、文案、性能和相关自测。

⚠️ **不要**跑 make-update-manifest.py、**不要**碰 update-manifest.json ——
   它是推送期在主干(main)上统一生成的产物(红线第 4 条)。
   开发期生成既白做,两个并行分支各自生成还必然全文件冲突。

然后提交:
git add -A && git commit -m "写清你做了什么、为什么、怎么验的"

━━━ 七、合并由你自己做，推送才等用户 ━━━

提交完**接着自己回收合并**，不要回头问用户「要不要合并 / 确认合并吗」：

DYC_SMOKE_OK=1 bash scripts/回收.sh $NAME     # 改过 src/** 或 manifest.json
bash scripts/回收.sh $NAME                    # 纯脚本 / 文档任务

闸门全过即合并进 main 并自动清理本工作树；闸门红了就地修（改代码或改断言），
修完提交再跑一次。只有「真机现象拿不准」「冲突涉及别人的改动解不开」才问用户。

**不要自己推送** —— 推送等用户下令，你只报「已攒 N/5 点」。

━━━ 八、拿不准就问 ━━━

停下来问用户,不要自己猜。
宁可多问一句,也不要做出错误改动。
EOF